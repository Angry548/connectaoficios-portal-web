  test('CON-492, CON-493, CON-494, CON-495, CON-496 - listado, filtros, detalle y estado persistente de usuario QA', async ({ page }) => {
    const { token } = await principal()
    const user = await register(1)
    await register(1, unique('Control E2E'))
    await api('dotnet', `/api/admin/users/${user.id}/status`, { token, method: 'PATCH', data: { estado: 2 } })
    await login(page)
    await page.getByRole('link', { name: 'Usuarios', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Gestión de usuarios' })).toBeVisible()
    await expect(page.getByRole('table')).toBeVisible()
    await filter(page, 'Correo electrónico', user.correo)
    const row = page.getByRole('row').filter({ hasText: user.correo })
    await expect(row).toHaveCount(1)
    await expect(page.getByRole('row').filter({ has: page.getByRole('button', { name: /Acciones del usuario/ }) })).toHaveCount(1)
    await expect(row).toContainText(user.nombre)
    await expect(row.getByText('Inactivo', { exact: true })).toBeVisible()
    await action(page, row, 'Ver detalle')
    const detail = page.getByRole('dialog')
    await expect(detail).toContainText(user.nombre)
    await expect(detail).toContainText(user.correo)
    await expect(detail).toContainText('Cliente')
    await detail.getByRole('button', { name: 'Cerrar', exact: true }).click()
    for (const [label, text] of [['Activar', 'Activo'], ['Desactivar', 'Inactivo']]) {
      await action(page, row, label)
      await confirm(page, label)
      await expect(row.getByText(text, { exact: true })).toBeVisible()
      expect((await api('dotnet', `/api/admin/users/${user.id}`, { token })).estado).toBe(text)
      await page.reload()
      await filter(page, 'Correo electrónico', user.correo)
      await expect(row.getByText(text, { exact: true })).toBeVisible()
    }
  })

  test('CON-497, CON-498, CON-499, CON-500 - crear, actualizar, desactivar y eliminar administrador QA desde UI', async ({ page }) => {
    const { token } = await principal()
    const nombre = unique('Admin E2E')
    const correo = `e2e.admin.${randomUUID()}@example.test`
    let id
    try {
      await login(page)
      await page.getByRole('link', { name: 'Administradores', exact: true }).click()
      await page.getByRole('button', { name: 'Crear Administrador', exact: true }).click()
      const form = page.getByRole('dialog')
      await form.getByRole('textbox', { name: /^Nombre/ }).fill(nombre)
      await form.getByLabel('Correo electrónico', { exact: true }).fill(correo)
      await form.getByLabel('Contraseña', { exact: true }).fill(randomUUID() + '!Qa9')
      await form.getByRole('button', { name: 'Crear cuenta', exact: true }).click()
      await expect(form).toHaveCount(0)
      await filter(page, 'Correo electrónico', correo)
      const row = page.getByRole('row').filter({ hasText: correo })
      await expect(row).toContainText(nombre)
      let data = await api('dotnet', `/api/admin/accounts?correo=${encodeURIComponent(correo)}`, { token })
      expect(data.items).toHaveLength(1)
      id = data.items[0].id
      await action(page, row, 'Editar')
      await form.getByRole('textbox', { name: /^Nombre/ }).fill(nombre + ' Editado')
      await form.getByLabel('Teléfono', { exact: true }).fill('70000001')
      await form.getByRole('button', { name: 'Guardar cambios' }).click()
      await expect(form).toHaveCount(0)
      await page.reload()
      await filter(page, 'Correo electrónico', correo)
      await expect(row).toContainText(nombre + ' Editado')
      data = await api('dotnet', `/api/admin/accounts/${id}`, { token })
      expect(data.nombre).toBe(nombre + ' Editado')
      expect(data.telefono).toBe('70000001')
      await action(page, row, 'Desactivar')
      await confirm(page, 'Desactivar')
      await page.reload()
      await filter(page, 'Correo electrónico', correo)
      await expect(row.getByText('Inactivo', { exact: true })).toBeVisible()
      expect((await api('dotnet', `/api/admin/accounts/${id}`, { token })).estado).toBe('Inactivo')
      await action(page, row, 'Eliminar')
      await confirm(page, 'Eliminar')
      await expect(row).toHaveCount(0)
      await page.reload()
      await filter(page, 'Correo electrónico', correo)
      await expect(row).toHaveCount(0)
      await api('dotnet', `/api/admin/accounts/${id}`, { token, status: 404 })
      id = undefined
    } finally {
      if (id) await api('dotnet', `/api/admin/accounts/${id}`, { token, method: 'DELETE' })
    }
  })

